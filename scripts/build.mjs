import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import vm from 'node:vm';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const core = await readFile(resolve(root, 'src/core.cjs'), 'utf8');
const client = await readFile(resolve(root, 'src/client.cjs'), 'utf8');
const bundled = client.replace("require('./core.cjs')", `(() => { const module = { exports: {} };\n${core}\nreturn module.exports; })()`);
if (bundled === client) throw new Error('客户端核心模块替换失败。');
const output = `// Generated by scripts/build.mjs; edit src files, not this bundle.\nwindow.__ModuleLoader__.load({\n id: 'dsh-model-roles',\n factory: (require) => {\n const module = { exports: {} };\n${bundled}\n return module.exports;\n }\n});\n`;
new vm.Script(output, { filename: 'dsh-model-roles/client.js' });
await mkdir(resolve(root, 'lib'), { recursive: true });
await writeFile(resolve(root, 'lib/client.js'), output);
await writeFile(resolve(root, 'lib/index.js'), `// UI-only host half; no requests, tools or settings changes.\nexport function apply() {}\nexport const meta = {\n zh: { title: '规划／执行模型', description: '双模型预设与快捷切换，不自动改变权限模式。' },\n en: { title: 'Planning / Execution Models', description: 'Two model presets with manual keyboard switching.' }\n};\n`);
console.log('Built dsh-model-roles browser bundle and UI-only host entry.');
